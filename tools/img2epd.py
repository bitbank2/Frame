#!/usr/bin/env python3
"""
img2epd.py - Convert image to 4bpp E Ink format for E2803 driver IC

EPD color nibble mapping (4bpp):
  0x0 = Black
  0x1 = White
  0x2 = Yellow
  0x3 = Red
  0x5 = Blue
  0x6 = Green

Each byte holds 2 pixels:
  high nibble = even x pixel
  low  nibble = odd  x pixel

Section size: 800 x 720 pixels = 288,000 bytes per driver IC
Full display:  8 sections = 6400 x 720 pixels total

Usage:
  pip install Pillow
  python3 img2epd.py image.png             # single section (800x720)
  python3 img2epd.py image.png --full      # full display (6400x720), split into 8 sections
  python3 img2epd.py image.png --section 2 # output only section 2 of full image
"""

import sys
import os
import argparse
from PIL import Image
import numpy as np

# ── EPD color palette (nibble value → RGB) ─────────────────────────────────
EPD_PALETTE = {
    0x0: (0,   0,   0),    # Black
    0x1: (255, 255, 255),  # White
    0x2: (255, 223, 0),    # Yellow
    0x3: (196, 2,   51),   # Red
    0x5: (0,   86,  163),  # Blue
    0x6: (0,   155, 72),   # Green
}

SECTION_W = 800
SECTION_H = 720
NUM_SECTIONS = 8
FULL_W = SECTION_W * NUM_SECTIONS  # 6400
BYTES_PER_SECTION = SECTION_W * SECTION_H // 2  # 288000

# ── Color quantization ────────────────────────────────────────────────────────
palette_rgb = np.array(list(EPD_PALETTE.values()), dtype=np.float32)
palette_keys = list(EPD_PALETTE.keys())

def nearest_color(pixel_rgb):
    """Return nibble value of closest EPD color to given RGB pixel."""
    diff = palette_rgb - np.array(pixel_rgb, dtype=np.float32)
    dist = np.sum(diff ** 2, axis=1)
    return palette_keys[int(np.argmin(dist))]

def image_to_nibbles(img):
    """Convert PIL image to a list of 4bpp nibble values (one per pixel)."""
    img = img.convert("RGB")
    w, h = img.size
    pixels = np.array(img, dtype=np.float32)  # shape: (h, w, 3)

    nibbles = np.zeros((h, w), dtype=np.uint8)
    for nib_val, rgb in EPD_PALETTE.items():
        diff = pixels - np.array(rgb, dtype=np.float32)
        dist = np.sum(diff ** 2, axis=2)
        if nib_val == palette_keys[0]:
            best_dist = dist
            nibbles[:, :] = nib_val
        else:
            better = dist < best_dist
            best_dist = np.where(better, dist, best_dist)
            nibbles[better] = nib_val

    return nibbles  # shape: (h, w)

def nibbles_to_bytes(nibbles):
    """Pack nibble array (h×w) into 4bpp byte array."""
    h, w = nibbles.shape
    assert w % 2 == 0, "Width must be even"
    even = nibbles[:, 0::2].astype(np.uint8)  # even columns
    odd  = nibbles[:, 1::2].astype(np.uint8)  # odd columns
    packed = (even << 4) | odd
    return packed.flatten().tobytes()

# ── Header generation ─────────────────────────────────────────────────────────
def bytes_to_c_array(data, var_name, section_idx=None):
    """Format byte data as a C array declaration."""
    n = len(data)
    lines = []
    label = f"{var_name}" if section_idx is None else f"{var_name}_sec{section_idx}"
    lines.append(f"// {n} bytes  ({SECTION_W}x{SECTION_H} @ 4bpp)")
    lines.append(f"static const uint8_t {label}[{n}] = {{")
    for i in range(0, n, 16):
        chunk = data[i:i+16]
        hex_str = ", ".join(f"0x{b:02X}" for b in chunk)
        lines.append(f"    {hex_str},")
    lines.append("};")
    return "\n".join(lines)

def write_header(sections_data, var_name, out_path, source_file):
    guard = var_name.upper() + "_H"
    lines = []
    lines.append(f"// Auto-generated by img2epd.py from: {source_file}")
    lines.append(f"// {len(sections_data)} section(s), {SECTION_W}x{SECTION_H} each, 4bpp E2803 format")
    lines.append(f"#pragma once")
    lines.append(f"#include <stdint.h>")
    lines.append("")

    for i, data in enumerate(sections_data):
        lines.append(bytes_to_c_array(data, var_name, i if len(sections_data) > 1 else None))
        lines.append("")

    # If multiple sections, add a pointer array
    if len(sections_data) > 1:
        lines.append(f"static const uint8_t* {var_name}_sections[{len(sections_data)}] = {{")
        for i in range(len(sections_data)):
            lines.append(f"    {var_name}_sec{i},")
        lines.append("};")
        lines.append("")

    with open(out_path, "w") as f:
        f.write("\n".join(lines))

    print(f"Written: {out_path}  ({os.path.getsize(out_path)//1024} KB)")

# ── Main ──────────────────────────────────────────────────────────────────────
def main():
    parser = argparse.ArgumentParser(description="Convert image to EPD 4bpp C header")
    parser.add_argument("image", help="Input image file")
    parser.add_argument("--full", action="store_true",
                        help=f"Treat as full display ({FULL_W}x{SECTION_H}), split into {NUM_SECTIONS} sections")
    parser.add_argument("--section", type=int, default=None,
                        help="Output only this section index (0-7) from full image")
    parser.add_argument("--name", default=None,
                        help="Variable name prefix (default: image filename without extension)")
    parser.add_argument("--out", default=None,
                        help="Output .h file path (default: <name>.h in ../include/)")
    args = parser.parse_args()

    img = Image.open(args.image)
    base = args.name or os.path.splitext(os.path.basename(args.image))[0]
    base = base.replace("-", "_").replace(" ", "_")

    out_dir = os.path.join(os.path.dirname(__file__), "..", "include")
    out_path = args.out or os.path.join(out_dir, f"{base}.h")

    if args.full or args.section is not None:
        # Full display mode: resize to 6400x720, split into 8 sections
        target_w, target_h = FULL_W, SECTION_H
        print(f"Resizing to {target_w}x{target_h} (full display)...")
        img = img.resize((target_w, target_h), Image.LANCZOS)
        nibbles = image_to_nibbles(img)

        if args.section is not None:
            # Single section from full image
            sec = args.section
            sec_nibbles = nibbles[:, sec*SECTION_W:(sec+1)*SECTION_W]
            data = nibbles_to_bytes(sec_nibbles)
            print(f"Section {sec}: {len(data)} bytes")
            write_header([data], base, out_path, args.image)
        else:
            # All 8 sections
            sections_data = []
            for i in range(NUM_SECTIONS):
                sec_nibbles = nibbles[:, i*SECTION_W:(i+1)*SECTION_W]
                data = nibbles_to_bytes(sec_nibbles)
                sections_data.append(data)
                print(f"Section {i}: {len(data)} bytes")
            write_header(sections_data, base, out_path, args.image)
    else:
        # Single section mode: resize to 800x720
        print(f"Resizing to {SECTION_W}x{SECTION_H} (single section)...")
        img = img.resize((SECTION_W, SECTION_H), Image.LANCZOS)
        nibbles = image_to_nibbles(img)
        data = nibbles_to_bytes(nibbles)
        print(f"Data: {len(data)} bytes")
        write_header([data], base, out_path, args.image)

    print(f"\nUsage in firmware:")
    print(f'  #include "{os.path.basename(out_path)}"')
    if args.full and args.section is None:
        print(f"  // Send each section to its driver IC:")
        print(f"  for(int i = 0; i < {NUM_SECTIONS}; i++)")
        print(f"      epdWriteImage(i, {base}_sections[i], {BYTES_PER_SECTION});")
    else:
        print(f"  epdWriteImage(0, {base}_sec0, {BYTES_PER_SECTION});")

if __name__ == "__main__":
    main()
